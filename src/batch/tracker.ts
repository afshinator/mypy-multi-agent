/**
 * Batch tracker adapter: the only module that talks to the issue tracker.
 *
 * Two details decide its shape. `gh issue view --json comments` hands back
 * GraphQL node ids (`IC_kw…`), which the REST PATCH cannot address, so comments
 * are read from the REST listing for their numeric ids. And `gh issue comment`
 * only knows `--edit-last` — the last comment of the current user — so the
 * marker comment is edited through the REST endpoint instead.
 *
 * The issue body is never written: there is no body argument anywhere here.
 */
import { execFile } from "node:child_process";

export type Exec = (args: string[], stdin?: string) => Promise<string>;

export interface CommentRef {
  id: number;
  body: string;
}

export interface TicketSnapshot {
  number: number;
  title: string;
  body: string;
  state: string;
  updatedAt: string;
  labels: string[];
  comments: CommentRef[];
}

export interface Tracker {
  view(n: number): Promise<TicketSnapshot>;
  upsertMarkerComment(
    n: number,
    marker: string,
    text: string,
  ): Promise<{ action: "created" | "edited"; id: number }>;
  addLabel(n: number, label: string): Promise<void>;
  removeLabel(n: number, label: string): Promise<void>;
}

/** Required by the triage skill on every comment posted during triage. */
export const AI_DISCLAIMER = "> *This was generated by AI during triage.*";

/** Disclaimer first, then the marker, then the body. */
export function commentBody(marker: string, text: string): string {
  return `${AI_DISCLAIMER}\n\n${marker}\n${text}`;
}

export function findMarker(comments: readonly CommentRef[], marker: string): number | undefined {
  return comments.find((comment) => comment.body.includes(marker))?.id;
}

const ISSUES = "repos/{owner}/{repo}/issues";

const defaultExec: Exec = (args, stdin) =>
  new Promise((resolve, reject) => {
    const child = execFile("gh", args, (err, stdout) => (err ? reject(err) : resolve(stdout)));
    if (stdin !== undefined) child.stdin?.end(stdin);
  });

export function createGithubTracker(exec: Exec = defaultExec): Tracker {
  const markerId = async (n: number, marker: string): Promise<number | undefined> => {
    const raw = await exec(["api", `${ISSUES}/${n}/comments`, "--paginate"]);
    return findMarker(JSON.parse(raw) as CommentRef[], marker);
  };

  return {
    async view(n) {
      const raw = await exec([
        "issue",
        "view",
        String(n),
        "--json",
        "number,title,body,state,updatedAt,labels",
      ]);
      const ticket = JSON.parse(raw) as Omit<TicketSnapshot, "comments" | "labels"> & {
        labels: { name: string }[];
      };
      const comments = JSON.parse(
        await exec(["api", `${ISSUES}/${n}/comments`, "--paginate"]),
      ) as CommentRef[];
      return {
        number: ticket.number,
        title: ticket.title,
        body: ticket.body,
        state: ticket.state,
        updatedAt: ticket.updatedAt,
        labels: ticket.labels.map((label) => label.name),
        comments: comments.map(({ id, body }) => ({ id, body })),
      };
    },

    async upsertMarkerComment(n, marker, text) {
      const body = commentBody(marker, text);
      const existing = await markerId(n, marker);
      if (existing !== undefined) {
        await exec(
          ["api", "--method", "PATCH", `${ISSUES}/comments/${existing}`, "-f", "body=@-"],
          body,
        );
        return { action: "edited", id: existing };
      }
      const created = await exec(
        ["api", "--method", "POST", `${ISSUES}/${n}/comments`, "-f", "body=@-"],
        body,
      );
      const { id } = JSON.parse(created) as { id?: number };
      if (typeof id !== "number") throw new Error("gh returned no comment id");
      return { action: "created", id };
    },

    async addLabel(n, label) {
      await exec(["issue", "edit", String(n), "--add-label", label]);
    },

    async removeLabel(n, label) {
      await exec(["issue", "edit", String(n), "--remove-label", label]);
    },
  };
}
