describe("lockfile resolution", () => {
  it("strips trailing commas and comments without touching URLs inside strings", () => {
    const jsonc = `{
      // a comment
      "url": "https://registry.example/x", /* inline */
      "packages": { "a": ["a@1.2.3", "", {}, "sha"], },
    }`;
    const parsed = JSON.parse(stripJsonc(jsonc)) as {
      url: string;
      packages: Record<string, string[]>;
    };
    expect(parsed.url).toBe("https://registry.example/x");
    expect(parsed.packages.a?.[0]).toBe("a@1.2.3");
  });

  it("resolves from bun.lock, including a scoped package", () => {
    const root = repo({
      "bun.lock":
        '{ "packages": { "undici": ["undici@8.10.2", "", {}], "@scope/pkg": ["@scope/pkg@0.4.1", "", {}], }, }',
    });
    expect(resolveInstalled(root, "undici")).toEqual({
      package: "undici",
      version: "8.10.2",
      source: "bun.lock",
    });
    expect(resolveInstalled(root, "@scope/pkg")?.version).toBe("0.4.1");
  });

  it("resolves from package-lock v3 and prefers the shallowest duplicate", () => {
    const root = repo({
      "package-lock.json": JSON.stringify({
        lockfileVersion: 3,
        packages: {
          "": { name: "x" },
          "node_modules/react": { version: "19.2.3" },
          "node_modules/a/node_modules/react": { version: "18.0.0" },
        },
      }),
    });
    expect(resolveInstalled(root, "react")).toEqual({
      package: "react",
      version: "19.2.3",
      source: "package-lock.json",
    });
  });

  it("falls back to a v1 dependencies map", () => {
    const root = repo({
      "package-lock.json": JSON.stringify({
        lockfileVersion: 1,
        dependencies: { lodash: { version: "4.17.21" } },
      }),
    });
    expect(resolveInstalled(root, "lodash")?.version).toBe("4.17.21");
  });

  it("resolves from a real pnpm v9 lockfile: importer wins, peer suffix stripped, scoped, store duplicate", () => {
    const root = repo({ "pnpm-lock.yaml": PNPM_V9 });
    // direct dependency, declared in the root importer
    expect(resolveInstalled(root, "typebox")).toEqual({
      package: "typebox",
      version: "1.3.35",
      source: "pnpm-lock.yaml",
    });
    // scoped direct dependency
    expect(resolveInstalled(root, "@types/node")).toEqual({
      package: "@types/node",
      version: "24.19.1",
      source: "pnpm-lock.yaml",
    });
    // peer suffix stripped from the importer version
    expect(resolveInstalled(root, "@earendil-works/pi-coding-agent")?.version).toBe("1.0.2");
    // transitive-only package at two store versions -> highest
    expect(resolveInstalled(root, "agent-base")?.version).toBe("9.0.0");
    // scoped store key, not a direct dependency
    expect(resolveInstalled(root, "@anthropic-ai/sdk")?.version).toBe("0.129.0");
  });

  it("resolves from a real yarn v1 lockfile, including scoped and range-keyed blocks", () => {
    const root = repo({ "yarn.lock": YARN_V1 });
    expect(resolveInstalled(root, "undici")).toEqual({
      package: "undici",
      version: "5.28.5",
      source: "yarn.lock",
    });
    expect(resolveInstalled(root, "@types/node")).toEqual({
      package: "@types/node",
      version: "20.14.0",
      source: "yarn.lock",
    });
    expect(resolveInstalled(root, "@fastify/busboy")?.version).toBe("2.1.1");
    expect(resolveInstalled(root, "undici-types")?.version).toBe("5.26.5");
  });

  it("resolves a yarn v1 package present at two versions to the higher one", () => {
    expect(resolveInstalled(repo({ "yarn.lock": YARN_DUP }), "undici")?.version).toBe("5.28.5");
  });

  it("returns null rather than guessing for an out-of-scope format or an absent lockfile", () => {
    // pnpm v6 uses a different grammar and is out of scope
    expect(
      resolveInstalled(
        repo({
          "pnpm-lock.yaml":
            "lockfileVersion: '6.0'\n\npackages:\n\n  /x@1.2.3:\n    resolution: {integrity: sha512-x}\n",
        }),
        "x",
      ),
    ).toBeNull();
    // yarn berry has no `version "x"` lines and is out of scope
    expect(
      resolveInstalled(
        repo({
          "yarn.lock":
            '__metadata:\n  version: 8\n\n"x@npm:1.2.3":\n  version: 1.2.3\n  resolution: "x@npm:1.2.3"\n',
        }),
        "x",
      ),
    ).toBeNull();
    expect(resolveInstalled(repo({}), "x")).toBeNull();
  });

  it("reads the package name aislop puts in front of an advisory", () => {
    expect(packageFromAdvisory("undici (high) — undici vulnerable to DoS")).toBe("undici");
    expect(packageFromAdvisory("@scope/pkg (high) — x")).toBe("@scope/pkg");
    expect(packageFromAdvisory("no package named here")).toBeNull();
  });
});
